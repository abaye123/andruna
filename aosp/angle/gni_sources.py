#!/usr/bin/env python3
"""Reads source lists from ANGLE's .gni files and writes them as CMake lists.

Usage: gni_sources.py <angle dir> <output .cmake file>

Only plain list assignments are read: `name = [ "a", "b" ]` and
`name = other + [ ... ]`, wherever they appear in the file (also inside
`if` blocks). Conditional `+=` additions are not evaluated; the CMake glue
adds the ones the Windows D3D11 build needs by name. Paths are made
relative to the ANGLE root. Each output variable is `ANGLE_<NAME>` and holds
only compiled sources (.c, .cc, .cpp).
"""

import re
import sys
from pathlib import Path

# (gni file relative to the ANGLE root, directory its paths are relative to,
#  list variables to export)
FILES = [
    ("src/libGLESv2.gni", "", [
        "libangle_common_sources", "libangle_common_shader_state_sources",
        "xxhash_sources", "libangle_image_util_sources",
        "libangle_gpu_info_util_sources", "libangle_gpu_info_util_win_sources",
        "libangle_sources", "libglesv2_entry_point_sources", "libglesv2_sources",
        "libegl_sources",
    ]),
    ("src/compiler.gni", "", [
        "angle_translator_sources", "angle_translator_essl_symbol_table_sources",
        "angle_translator_essl_sources", "angle_translator_glsl_base_sources",
        "angle_translator_hlsl_sources", "angle_preprocessor_sources",
    ]),
    ("src/libANGLE/renderer/d3d/d3d_backend.gni", "src/libANGLE/renderer/d3d", [
        "d3d_shared_sources", "d3d11_backend_sources",
    ]),
]

COMPILED = (".c", ".cc", ".cpp")


def strip_comments(text):
    return "\n".join(line.split("#", 1)[0] if '"' not in line else line
                     for line in text.splitlines())


def parse_assignments(text):
    """name -> raw expression text, for the first `name = ...` of each name."""
    out = {}
    for m in re.finditer(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(?!=)", text, re.M):
        name = m.group(1)
        if name in out:
            continue
        # The expression runs until the brackets balance and no `+` follows.
        i, depth, expr = m.end(), 0, []
        while i < len(text) and text[i].isspace():
            i += 1
        while i < len(text):
            c = text[i]
            if c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
            elif c == "\n" and depth == 0:
                rest = text[i:].lstrip()
                if not rest.startswith("+") and not "".join(expr).rstrip().endswith("+"):
                    break
            expr.append(c)
            i += 1
        out[name] = "".join(expr)
    return out


def evaluate(name, assigns, seen=()):
    if name in seen:
        sys.exit(f"gni: recursive list {name}")
    expr = assigns.get(name)
    if expr is None:
        sys.exit(f"gni: list {name} not found")
    items = []
    for part in re.findall(r"\[[^\]]*\]|[A-Za-z_][A-Za-z0-9_]*", expr):
        if part.startswith("["):
            items += re.findall(r'"([^"]*)"', part)
        else:
            items += evaluate(part, assigns, seen + (name,))
    return items


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    angle = Path(sys.argv[1])
    lines = ["# Generated by aosp/angle/gni_sources.py; do not edit."]
    for gni, base, names in FILES:
        assigns = parse_assignments(strip_comments((angle / gni).read_text(encoding="utf-8")))
        for n in names:
            files = []
            for f in evaluate(n, assigns):
                p = f"{base}/{f}" if base else f
                if p.endswith(COMPILED) and p not in files:
                    files.append(p)
            lines.append(f"set(ANGLE_{n.upper()}")
            lines += [f'  "{p}"' for p in files]
            lines.append(")")
    out = Path(sys.argv[2])
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
