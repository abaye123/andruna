#!/usr/bin/env python3
"""Generates bionic's generated_android_ids.h (Android.bp genrule
`generated_android_ids`).

Soong runs build/make's fs_config_generator (`aidarray`) on
libcutils' private/android_filesystem_config.h, which is not fetched here.
The rule is the one documented in that header: every `#define AID_<NAME>
<value>` becomes the friendly name `<name>` (lower case); ranges
(`*_START`, `*_END`), offsets and the deprecated aliases AID_APP and
AID_USER are not ids.

Usage: gen_android_ids.py <android_filesystem_config.h> <out.h>
"""

import re
import sys
from pathlib import Path

SKIP = {"AID_APP", "AID_USER", "AID_USER_OFFSET"}


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    ids = []
    for m in re.finditer(r"^#define\s+(AID_[A-Z0-9_]+)\s+(\d+)", src.read_text(), re.M):
        name = m.group(1)
        if name in SKIP or name.endswith("_START") or name.endswith("_END"):
            continue
        friendly = name[4:].lower()
        if len(friendly) > 16:
            # bionic's table holds names of at most 16 characters; the
            # Android generator renames the few longer ids, which this
            # script does not know, so they are left out (getpwnam finds
            # them by number only).
            print(f"gen_android_ids.py: {name} left out (name longer than 16)", file=sys.stderr)
            continue
        ids.append((friendly, name))
    lines = [
        "// Generated by aosp/tools/gen_android_ids.py. Do not edit.",
        "#pragma once",
        "#include <private/android_filesystem_config.h>",
        "",
        "struct android_id_info {",
        "  const char name[17];",
        "  unsigned aid;",
        "};",
        "",
        "static const struct android_id_info android_ids[] = {",
    ]
    lines += [f'  {{ "{f}", {n}, }},' for f, n in ids]
    lines += ["};", "", "#define android_id_count (sizeof(android_ids) / sizeof(android_ids[0]))", ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    main()
