#!/usr/bin/env python3
"""Writes the C/C++ flag header for an .aconfig declaration file.

Android generates `<package>.h` (package dots replaced by underscores) with
the aconfig tool. The header declares, for every flag:

  C++:  namespace <package as namespaces> { bool <flag>(); }
  C:    bool <package_underscored>_<flag>(void);
  both: #define <PACKAGE_UNDERSCORED>_<FLAG> <value>

This script writes the same API with every flag fixed at the aconfig
default value (disabled). It has no flag storage and no overrides: flags
are compile-time constants until Andruna has a flag configuration.

Usage: aconfig_cc.py <file.aconfig> <output directory>
"""

import os
import re
import sys


def parse(text):
    package = None
    flags = []
    # Drop comments, then read top-level `package:` and `flag { name: ... }`.
    text = re.sub(r"#[^\n]*", "", text)
    m = re.search(r'^\s*package\s*:\s*"([^"]+)"', text, re.M)
    if m:
        package = m.group(1)
    for block in re.finditer(r"\bflag\s*\{", text):
        depth = 0
        i = block.end() - 1
        while i < len(text):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        body = text[block.end():i]
        # The flag's own name is the first `name:` at nesting depth 0.
        flat = re.sub(r"\{[^{}]*\}", "", body)
        n = re.search(r'\bname\s*:\s*"([^"]+)"', flat)
        if n:
            flags.append(n.group(1))
    if not package:
        raise SystemExit("no package declaration found")
    return package, flags


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src, outdir = sys.argv[1], sys.argv[2]
    with open(src, encoding="utf-8") as f:
        package, flags = parse(f.read())
    under = package.replace(".", "_")
    ns = package.replace(".", "::")
    lines = [
        "// Generated by aosp/tools/aconfig_cc.py from " + os.path.basename(src) + ".",
        "// Every flag is fixed at its default value (disabled).",
        "#pragma once",
        "",
    ]
    # Read-only flags also get a macro with their value, as aconfig does.
    for fl in flags:
        lines.append("#define " + under.upper() + "_" + fl.upper() + " false")
    lines += [
        "",
        "#ifdef __cplusplus",
        "namespace " + ns + " {",
    ]
    for fl in flags:
        lines.append("inline constexpr bool " + fl + "() { return false; }")
    lines += [
        "}  // namespace " + ns,
        "#define ANDRUNA_ACONFIG_INLINE inline",
        "#else",
        "#include <stdbool.h>",
        "#define ANDRUNA_ACONFIG_INLINE static inline",
        "#endif",
        "",
    ]
    for fl in flags:
        lines.append(
            "ANDRUNA_ACONFIG_INLINE bool " + under + "_" + fl + "(void) { return false; }"
        )
    lines += ["#undef ANDRUNA_ACONFIG_INLINE", ""]
    os.makedirs(outdir, exist_ok=True)
    out = os.path.join(outdir, under + ".h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
