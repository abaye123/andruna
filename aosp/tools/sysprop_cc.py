#!/usr/bin/env python3
"""Writes the C++ accessors for a .sysprop description file.

Android generates `<name>.sysprop.h` and `<name>.sysprop.cpp` from a
`.sysprop` file (Soong's sysprop_library, tool sysprop_cpp). Each `prop`
becomes, in the namespace of `module` (dots become `::`):

  std::optional<T> <api_name>();                   every access
  bool <api_name>(const std::optional<T>& value);  ReadWrite and Writeonce

T is bool (Boolean), std::int32_t (Integer), std::int64_t (Long), double
(Double) or std::string (String). Readers parse the system property
`prop_name` the way sysprop_cpp does: an empty or unparsable value gives
std::nullopt. Enum and list types are not supported (no Andruna user yet).

Usage: sysprop_cc.py <file.sysprop> <output directory>
"""

import re
import sys
from pathlib import Path

TYPES = {"Boolean": "bool", "Integer": "std::int32_t", "Long": "std::int64_t",
         "Double": "double", "String": "std::string"}

PARSE = {
    "Boolean": """    if (v == "1" || v == "true") return true;
    if (v == "0" || v == "false") return false;
    return std::nullopt;""",
    "Integer": """    std::int32_t r;
    if (!android::base::ParseInt(v, &r)) return std::nullopt;
    return r;""",
    "Long": """    std::int64_t r;
    if (!android::base::ParseInt(v, &r)) return std::nullopt;
    return r;""",
    "Double": """    char* end = nullptr;
    errno = 0;
    double r = std::strtod(v.c_str(), &end);
    if (v.empty() || errno != 0 || *end != '\\0') return std::nullopt;
    return r;""",
    "String": """    if (v.empty()) return std::nullopt;
    return v;""",
}

FORMAT = {"Boolean": 'value ? "true" : "false"', "Integer": "std::to_string(value)",
          "Long": "std::to_string(value)", "Double": "std::to_string(value)", "String": "value"}


def parse(text):
    text = re.sub(r"#[^\n]*", "", text)
    module = re.search(r'module\s*:\s*"([^"]+)"', text).group(1)
    props = []
    for m in re.finditer(r"prop\s*\{([^}]*)\}", text):
        body = m.group(1)
        fields = dict(re.findall(r'(\w+)\s*:\s*"?([^"\s]+)"?', body))
        props.append(fields)
    return module, props


def main():
    src, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    module, props = parse(src.read_text(encoding="utf-8"))
    ns = module.replace(".", "::")
    name = src.name
    h = [f"// Generated by aosp/tools/sysprop_cc.py from {name}. Do not edit.",
         "#pragma once", "", "#include <cstdint>", "#include <optional>", "#include <string>", "",
         f"namespace {ns} {{", ""]
    c = [f"// Generated by aosp/tools/sysprop_cc.py from {name}. Do not edit.",
         f'#include "{name}.h"', "", "#include <cerrno>", "#include <cstdlib>", "",
         "#include <android-base/parseint.h>", "#include <android-base/properties.h>", "",
         f"namespace {ns} {{", ""]
    for p in props:
        t = p["type"]
        if t not in TYPES:
            sys.exit(f"{name}: type {t} is not supported")
        ct, api, prop = TYPES[t], p["api_name"], p.get("prop_name", p["api_name"])
        h.append(f"std::optional<{ct}> {api}();")
        c += [f"std::optional<{ct}> {api}() {{",
              f'    std::string v = android::base::GetProperty("{prop}", "");',
              PARSE[t], "}", ""]
        if p.get("access") in ("ReadWrite", "Writeonce"):
            h.append(f"bool {api}(const std::optional<{ct}>& value);")
            c += [f"bool {api}(const std::optional<{ct}>& v) {{",
                  f"    if (!v) return android::base::SetProperty(\"{prop}\", \"\");",
                  f"    const auto& value = *v;",
                  f'    return android::base::SetProperty("{prop}", {FORMAT[t]});',
                  "}", ""]
    h += ["", f"}}  // namespace {ns}", ""]
    c += [f"}}  // namespace {ns}", ""]
    outdir.mkdir(parents=True, exist_ok=True)
    for path, lines in ((outdir / f"{name}.h", h), (outdir / f"{name}.cpp", c)):
        text = "\n".join(lines)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
