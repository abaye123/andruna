"""Generates Java classes from event log tag files (.logtags), the classes
Soong's `logtags` source type produces: one class per file, named after the
file, in the package of its `option java_package` line, with a constant per
tag and a write method that calls android.util.EventLog.writeEvent.

Format (system/logging/logcat/event.logtags): `<number> <name>
(<column>|<type>[|<unit>]),...` with types 1 int, 2 long, 3 string, 4 list,
5 float.

Usage: gen_logtags.py <out_dir> <file.logtags>...
"""

import os
import re
import sys

JAVA_TYPES = {"1": "int", "2": "long", "3": "String", "4": "Object[]", "5": "float"}


def camel(name, upper_first):
    parts = [p for p in re.split(r"[_\W]+", name) if p]
    s = "".join(p[:1].upper() + p[1:] for p in parts)
    if upper_first:
        return s
    s = s[:1].lower() + s[1:]
    return s + "_" if s in KEYWORDS else s


KEYWORDS = {"package", "class", "default", "new", "int", "long", "float", "final",
            "interface", "static", "this", "switch", "case", "return", "throw"}


def parse(path):
    package, tags = None, []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if line.startswith("option"):
                parts = line.split()
                if len(parts) >= 3 and parts[1] == "java_package":
                    package = parts[2].rstrip(";")
                continue
            m = re.match(r"(\S+)\s+(\S+)\s*(.*)$", line)
            number, name, desc = m.group(1), m.group(2), m.group(3).strip()
            cols = []
            for c in re.findall(r"\(([^)]*)\)", desc):
                fields = c.split("|")
                cols.append((fields[0].strip(), JAVA_TYPES[fields[1].strip()]))
            tags.append((number, name, cols))
    return package, tags


def emit(out_dir, path):
    package, tags = parse(path)
    if not package:
        raise SystemExit(f"{path}: no java_package option")
    cls = os.path.splitext(os.path.basename(path))[0]
    lines = [
        "// Generated by aosp/framework/gen_logtags.py from " + os.path.basename(path) + ".\n",
        f"package {package};\n\n",
        f"/** @hide */\npublic class {cls} {{\n",
        f"  private {cls}() {{ }}  // don't instantiate\n\n",
    ]
    for number, name, cols in tags:
        if number == "?":
            raise SystemExit(f"{path}: tag {name} has no number")
        const = name.upper()
        lines.append(f"  /** {number} {name} */\n  public static final int {const} = {number};\n\n")
    for number, name, cols in tags:
        const = name.upper()
        params = ", ".join(f"{t} {camel(c, False)}" for c, t in cols)
        args = "".join(f", {camel(c, False)}" for c, _ in cols)
        lines.append(f"  public static void write{camel(name, True)}({params}) {{\n")
        lines.append(f"    android.util.EventLog.writeEvent({const}{args});\n  }}\n\n")
    lines.append("}\n")
    d = os.path.join(out_dir, *package.split("."))
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, cls + ".java"), "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(lines))


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    for p in argv[2:]:
        emit(argv[1], p)
    print(f"logtags: {len(argv) - 2} files")


if __name__ == "__main__":
    main(sys.argv)
