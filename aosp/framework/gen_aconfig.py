"""Generates the Java flag classes of aconfig declaration files.

Soong generates, for each java_aconfig_library, a package with Flags,
FeatureFlags, FeatureFlagsImpl, CustomFeatureFlags and FakeFeatureFlagsImpl.
This script writes the same API with every flag fixed at the value it has
when no release configuration sets it: disabled. Andruna has no flag
configuration yet; the native side (aosp/tools/aconfig_cc.py) makes the same
choice, so Java and native code agree.

Usage: gen_aconfig.py <out_dir> <file.aconfig>...
"""

import os
import re
import sys


def _block_end(text, start):
    depth, i = 0, start
    while True:
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        elif c == '"':
            i = text.index('"', i + 1)
        i += 1


def parse(path):
    """(package, [{"name": ...}]) of one .aconfig text proto file."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    lines = [ln for ln in text.splitlines() if not ln.lstrip().startswith("#")]
    text = "\n".join(lines)
    m = re.search(r'^\s*package:\s*"([^"]+)"', text, re.M)
    if not m:
        if not text.strip():
            return None, []  # an empty declaration file
        raise SystemExit(f"{path}: no package")
    flags = []
    for block in re.finditer(r"\bflag\s*\{", text):
        end = _block_end(text, block.end() - 1)
        body = text[block.end():end]
        nm = re.search(r'^\s*name:\s*"([^"]+)"', body, re.M)
        if not nm:
            raise SystemExit(f"{path}: flag without name")
        flags.append({"name": nm.group(1)})
    return m.group(1), flags


def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


HEADER = ("// Generated by aosp/framework/gen_aconfig.py. Every flag is fixed at\n"
          "// its default value (disabled).\n")


def emit(out_dir, package, names):
    pkg_dir = os.path.join(out_dir, *package.split("."))
    os.makedirs(pkg_dir, exist_ok=True)
    head = HEADER + f"package {package};\n\n"
    methods = [(n, camel(n)) for n in names]
    files = {}

    b = [head, "/** @hide */\npublic final class Flags {\n"]
    for n, m in methods:
        b.append(f'    /** @hide */\n    public static final String FLAG_{n.upper()} = "{package}.{n}";\n')
    for n, m in methods:
        b.append(f"    /** @hide */\n    public static boolean {m}() {{\n        return FEATURE_FLAGS.{m}();\n    }}\n")
    b.append("    private static FeatureFlags FEATURE_FLAGS = new FeatureFlagsImpl();\n")
    b.append("    private Flags() {}\n}\n")
    files["Flags"] = b

    b = [head, "/** @hide */\npublic interface FeatureFlags {\n"]
    for n, m in methods:
        b.append(f"    boolean {m}();\n")
    b.append("}\n")
    files["FeatureFlags"] = b

    b = [head, "/** @hide */\npublic final class FeatureFlagsImpl implements FeatureFlags {\n"]
    for n, m in methods:
        b.append(f"    @Override\n    public boolean {m}() {{\n        return false;\n    }}\n")
    b.append("}\n")
    files["FeatureFlagsImpl"] = b

    b = [head,
         "import java.util.Arrays;\nimport java.util.HashSet;\nimport java.util.List;\n"
         "import java.util.Set;\nimport java.util.function.BiPredicate;\n"
         "import java.util.function.Predicate;\n\n"
         "/** @hide */\npublic class CustomFeatureFlags implements FeatureFlags {\n"
         "    private BiPredicate<String, Predicate<FeatureFlags>> mGetValueImpl;\n\n"
         "    public CustomFeatureFlags(BiPredicate<String, Predicate<FeatureFlags>> getValueImpl) {\n"
         "        mGetValueImpl = getValueImpl;\n    }\n\n"]
    for n, m in methods:
        b.append(f"    @Override\n    public boolean {m}() {{\n"
                 f"        return getValue(Flags.FLAG_{n.upper()}, FeatureFlags::{m});\n    }}\n")
    b.append("    public boolean isFlagReadOnlyOptimized(String flagName) {\n"
             "        return false;\n    }\n\n"
             "    protected boolean getValue(String flagName, Predicate<FeatureFlags> getter) {\n"
             "        return mGetValueImpl.test(flagName, getter);\n    }\n\n"
             "    public List<String> getFlagNames() {\n        return Arrays.asList(")
    b.append(", ".join(f"Flags.FLAG_{n.upper()}" for n, _ in methods))
    b.append(");\n    }\n\n"
             "    private Set<String> mReadOnlyFlagsSet = new HashSet<>();\n}\n")
    files["CustomFeatureFlags"] = b

    b = [head,
         "import java.util.HashMap;\nimport java.util.Map;\n"
         "import java.util.function.Predicate;\n\n"
         "/** @hide */\npublic class FakeFeatureFlagsImpl extends CustomFeatureFlags {\n"
         "    private final Map<String, Boolean> mFlagMap = new HashMap<>();\n"
         "    private final FeatureFlags mDefaults;\n\n"
         "    public FakeFeatureFlagsImpl() {\n        this(null);\n    }\n\n"
         "    public FakeFeatureFlagsImpl(FeatureFlags defaults) {\n"
         "        super(null);\n        mDefaults = defaults;\n"
         "        for (String name : getFlagNames()) {\n            mFlagMap.put(name, null);\n        }\n    }\n\n"
         "    @Override\n"
         "    protected boolean getValue(String flagName, Predicate<FeatureFlags> getter) {\n"
         "        Boolean value = mFlagMap.get(flagName);\n"
         "        if (value != null) {\n            return value;\n        }\n"
         "        if (mDefaults != null) {\n            return getter.test(mDefaults);\n        }\n"
         "        throw new IllegalArgumentException(flagName + \" is not set\");\n    }\n\n"
         "    public void setFlag(String flagName, boolean value) {\n"
         "        if (!mFlagMap.containsKey(flagName)) {\n"
         "            throw new IllegalArgumentException(\"no such flag \" + flagName);\n        }\n"
         "        mFlagMap.put(flagName, value);\n    }\n\n"
         "    public void resetAll() {\n"
         "        for (Map.Entry<String, Boolean> entry : mFlagMap.entrySet()) {\n"
         "            entry.setValue(null);\n        }\n    }\n}\n"]
    files["FakeFeatureFlagsImpl"] = b

    for fname, body in files.items():
        with open(os.path.join(pkg_dir, fname + ".java"), "w", encoding="utf-8", newline="\n") as f:
            f.write("".join(body))


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    out_dir = argv[1]
    by_pkg = {}
    for path in argv[2:]:
        package, flags = parse(path)
        if package is None:
            continue
        by_pkg.setdefault(package, set()).update(f["name"] for f in flags)
    for package, names in sorted(by_pkg.items()):
        emit(out_dir, package, sorted(names))
    print(f"aconfig: {len(by_pkg)} packages, {sum(len(n) for n in by_pkg.values())} flags")


if __name__ == "__main__":
    main(sys.argv)
