#!/usr/bin/env python3
"""Writes the interim guest fonts.xml for the installed Windows fonts
(ADR 0046, point 3).

  python aosp/fonts/windows_fonts.py [--fonts-dir C:/Windows/Fonts]
                                     [--roboto-dir <dir>] [--out fonts.xml]

The result has Android's fonts.xml format: `sans-serif` (and its aliases)
on Roboto, then one fallback family per script on the Windows font that
covers it. File names are relative, so the file works with the Windows
font directory mounted as /system/fonts (Roboto copied next to it, or
mounted over it). A family whose files are not installed is left out and
listed on stderr. Nothing is copied: Windows fonts may be used on the
machine but not redistributed.
"""

import argparse
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

# (lang attribute, regular file, bold file or None). Order is fallback order,
# as in Android's fonts.xml.
FALLBACKS = [
    ("und-Arab", "segoeui.ttf", "segoeuib.ttf"),
    ("und-Hebr", "segoeui.ttf", "segoeuib.ttf"),
    ("und-Hebr", "arial.ttf", "arialbd.ttf"),
    ("und-Thai", "leelawui.ttf", "leelauib.ttf"),
    ("und-Armn", "segoeui.ttf", "segoeuib.ttf"),
    ("und-Geor", "segoeui.ttf", "segoeuib.ttf"),
    ("und-Deva", "nirmala.ttc", None),
    ("und-Beng", "nirmala.ttc", None),
    ("und-Guru", "nirmala.ttc", None),
    ("und-Gujr", "nirmala.ttc", None),
    ("und-Orya", "nirmala.ttc", None),
    ("und-Taml", "nirmala.ttc", None),
    ("und-Telu", "nirmala.ttc", None),
    ("und-Knda", "nirmala.ttc", None),
    ("und-Mlym", "nirmala.ttc", None),
    ("und-Sinh", "nirmala.ttc", None),
    ("und-Khmr", "leelawui.ttf", "leelauib.ttf"),
    ("und-Laoo", "leelawui.ttf", "leelauib.ttf"),
    ("und-Mymr", "mmrtext.ttf", "mmrtextb.ttf"),
    ("und-Ethi", "ebrima.ttf", "ebrimabd.ttf"),
    ("und-Cher", "gadugi.ttf", "gadugib.ttf"),
    ("und-Tibt", "himalaya.ttf", None),
    ("und-Mong", "monbaiti.ttf", None),
    ("und-Yiii", "msyi.ttf", None),
    ("und-Thaa", "mvboli.ttf", None),
    ("zh-Hans", "msyh.ttc", "msyhbd.ttc"),
    ("zh-Hant", "msjh.ttc", "msjhbd.ttc"),
    ("ja", "YuGothR.ttc", "YuGothB.ttc"),
    ("ko", "malgun.ttf", "malgunbd.ttf"),
    ("und-Zsye", "seguiemj.ttf", None),
    ("und-Zsym", "seguisym.ttf", None),
    (None, "seguihis.ttf", None),
]

SANS_ALIASES = ["arial", "helvetica", "tahoma", "verdana", "sans-serif-medium"]


def font(path, weight):
    return f'        <font weight="{weight}" style="normal">{path}</font>\n'


def generate(fonts_dir, roboto_dir):
    out = ['<?xml version="1.0" encoding="utf-8"?>\n',
           "<!-- Generated by aosp/fonts/windows_fonts.py (ADR 0046). -->\n",
           '<familyset version="23">\n',
           '    <family name="sans-serif">\n']
    roboto = roboto_dir / "Roboto-Regular.ttf"
    if not roboto.exists():
        print(f"warning: {roboto} missing; sans-serif falls back to Segoe UI", file=sys.stderr)
        out.append(font("segoeui.ttf", 400))
        out.append(font("segoeuib.ttf", 700))
    else:
        out.append('        <font weight="400" style="normal">Roboto-Regular.ttf\n'
                   '            <axis tag="wght" stylevalue="400" />\n        </font>\n')
        out.append('        <font weight="700" style="normal">Roboto-Regular.ttf\n'
                   '            <axis tag="wght" stylevalue="700" />\n        </font>\n')
    out.append("    </family>\n")
    for a in SANS_ALIASES:
        out.append(f'    <alias name="{a}" to="sans-serif" />\n')
    out.append('    <family name="serif">\n' + font("times.ttf", 400) + font("timesbd.ttf", 700) + "    </family>\n")
    out.append('    <family name="monospace">\n' + font("consola.ttf", 400) + font("consolab.ttf", 700) + "    </family>\n")
    missing = []
    for lang, regular, bold in FALLBACKS:
        if not (fonts_dir / regular).exists():
            missing.append(f"{lang or 'symbols'}: {regular}")
            continue
        attr = f" lang={quoteattr(lang)}" if lang else ""
        out.append(f"    <family{attr}>\n" + font(regular, 400))
        if bold and (fonts_dir / bold).exists():
            out.append(font(bold, 700))
        out.append("    </family>\n")
    out.append("</familyset>\n")
    return "".join(out), missing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fonts-dir", default="C:/Windows/Fonts")
    ap.add_argument("--roboto-dir", default=None, help="directory with Roboto-Regular.ttf")
    ap.add_argument("--out", default="fonts.xml")
    a = ap.parse_args()
    fonts_dir = Path(a.fonts_dir)
    text, missing = generate(fonts_dir, Path(a.roboto_dir) if a.roboto_dir else fonts_dir)
    Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    for m in missing:
        print(f"not installed: {m}", file=sys.stderr)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
