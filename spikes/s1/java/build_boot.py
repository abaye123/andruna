"""Build a minimal ART boot classpath (core-oj, core-libart, core-icu4j) as
dex jars from the AOSP sources fetched by `cargo xtask fetch`, plus the S1
test programs Hello and Bench.

The build mirrors what Soong does for these modules at android-17.0.0_r1:

- The source lists come from libcore's openjdk_java_files.bp and
  non_openjdk_java_files.bp filegroups and from external/icu's
  android_icu4j Android.bp (src/main/java/android/icu/** and
  libcore_bridge/src/java/**).
- Like Soong's core-all bootstrap module, everything is compiled in one javac
  run into the java.base module (`--system=none`, `--patch-module`,
  java_version 21). The classes are then split back into the three
  libraries by the source file each class came from.
- aconfig flag classes are generated by gen_aconfig.py with every flag at
  its default value (disabled).
- Annotations Soong takes from projects outside this checkout
  (frameworks/base, tools/platform-compat, build/make aconfig) are replaced by
  stubs in stubs/, used at compile time only and not packaged, as Soong does
  with `libs`.
- Each library is dexed with d8 from a pinned Android build-tools release.

Usage (from anywhere):
    python spikes/s1/java/build_boot.py [--skip-verify]

Outputs go to out/s1/java/.
"""

import glob
import hashlib
import os
import re
import shutil
import struct
import subprocess
import sys
import urllib.request
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
AOSP = os.path.join(ROOT, "third_party", "aosp")
LIBCORE = os.path.join(AOSP, "libcore")
ICU4J = os.path.join(AOSP, "external", "icu", "android_icu4j")
OUT = os.path.join(ROOT, "out", "s1", "java")
TOOLS = os.path.join(ROOT, "out", "s1", "tools")

# Android SDK build-tools 37.0.0 for Windows, from Google's SDK repository
# (https://dl.google.com/android/repository/repository2-3.xml lists it with
# sha1 e9c97e26b5b5678002e9d3fed632c841ae62d99f). Its d8 is 9.2.4-dev.
BUILD_TOOLS_URL = "https://dl.google.com/android/repository/build-tools_r37_windows.zip"
BUILD_TOOLS_SHA256 = "68075aa319ed8a01cf1a565ed1e61a3c1a801dd49191c35851248dc293c33b1a"
BUILD_TOOLS_DIR = os.path.join(TOOLS, "build-tools-37")
D8_JAR = os.path.join(BUILD_TOOLS_DIR, "android-37.0", "lib", "d8.jar")
DEXDUMP = os.path.join(BUILD_TOOLS_DIR, "android-37.0", "dexdump.exe")

JAVA_VERSION = "21"
# d8 --min-api. The boot classpath targets the newest API level d8 knows, so
# d8 does not desugar anything the runtime implements itself.
MIN_API = "36"

# Sources left out of the build. Each entry is (path relative to its
# project, reason).
OKHTTP = "wraps com.android.okhttp (external/okhttp), which this minimal boot classpath leaves out"
EXCLUDED = [
    ("libcore/luni/src/main/java/libcore/net/http/Dns.java", OKHTTP),
    ("libcore/luni/src/main/java/libcore/net/http/HttpURLConnectionFactory.java", OKHTTP),
]


def log(msg):
    print(msg, flush=True)


def run(cmd, **kw):
    log("+ " + " ".join(cmd if len(cmd) < 12 else cmd[:12] + ["..."]))
    subprocess.run(cmd, check=True, **kw)


# --- build-tools -------------------------------------------------------------


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ensure_build_tools():
    if os.path.isfile(D8_JAR):
        return
    os.makedirs(TOOLS, exist_ok=True)
    zip_path = os.path.join(TOOLS, os.path.basename(BUILD_TOOLS_URL))
    if not os.path.isfile(zip_path) or sha256(zip_path) != BUILD_TOOLS_SHA256:
        log(f"downloading {BUILD_TOOLS_URL}")
        urllib.request.urlretrieve(BUILD_TOOLS_URL, zip_path)
    got = sha256(zip_path)
    if got != BUILD_TOOLS_SHA256:
        raise SystemExit(f"{zip_path}: sha256 {got}, expected {BUILD_TOOLS_SHA256}")
    # Extract into its own empty directory; the archive is untrusted data.
    if os.path.isdir(BUILD_TOOLS_DIR):
        shutil.rmtree(BUILD_TOOLS_DIR)
    os.makedirs(BUILD_TOOLS_DIR)
    with zipfile.ZipFile(zip_path) as z:
        for name in z.namelist():
            dest = os.path.normpath(os.path.join(BUILD_TOOLS_DIR, name))
            if not dest.startswith(BUILD_TOOLS_DIR + os.sep):
                raise SystemExit(f"{zip_path}: unsafe path {name}")
        z.extractall(BUILD_TOOLS_DIR)


# --- Android.bp filegroups ---------------------------------------------------


def parse_filegroups(paths):
    """Return {name: [srcs entries]} for every filegroup in the given .bp files."""
    groups = {}
    for path in paths:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        # Drop // comments but keep strings such as "//visibility:private".
        text = re.sub(r'("(?:[^"\\]|\\.)*")|//[^\n]*', lambda m: m.group(1) or "", text)
        for m in re.finditer(r"\bfilegroup\s*\{", text):
            depth, i = 0, m.end() - 1
            while True:
                c = text[i]
                if c == "{":
                    depth += 1
                elif c == "}":
                    depth -= 1
                    if depth == 0:
                        break
                elif c == '"':
                    i = text.index('"', i + 1)
                i += 1
            body = text[m.end():i]
            name = re.search(r'\bname:\s*"([^"]+)"', body).group(1)
            sm = re.search(r"\bsrcs:\s*\[(.*?)\]", body, re.S)
            srcs = re.findall(r'"([^"]+)"', sm.group(1)) if sm else []
            groups[name] = srcs
    return groups


def resolve(groups, name, base):
    out = []
    for s in groups[name]:
        if s.startswith(":"):
            out.extend(resolve(groups, s[1:], base))
        elif "**" in s:
            raise SystemExit(f"recursive glob in filegroup {name} not supported: {s}")
        elif "*" in s:
            out.extend(sorted(glob.glob(os.path.join(base, s.replace("/", os.sep)))))
        else:
            out.append(os.path.join(base, s.replace("/", os.sep)))
    return out


def glob_java(root):
    out = []
    for d, _, files in os.walk(root):
        for f in files:
            if f.endswith(".java"):
                out.append(os.path.join(d, f))
    return sorted(out)


def dedup(paths):
    seen, out = set(), []
    for p in paths:
        n = os.path.normcase(os.path.normpath(p))
        if n not in seen:
            seen.add(n)
            out.append(os.path.normpath(p))
    return out


def source_sets():
    groups = parse_filegroups(
        [os.path.join(LIBCORE, f) for f in ("openjdk_java_files.bp", "non_openjdk_java_files.bp")]
    )
    excluded = {os.path.normcase(os.path.normpath(os.path.join(AOSP, p))) for p, _ in EXCLUDED}

    def keep(paths):
        return [p for p in dedup(paths) if os.path.normcase(p) not in excluded]

    oj = keep(resolve(groups, "openjdk_java_files", LIBCORE))
    libart = keep(resolve(groups, "non_openjdk_java_files", LIBCORE))
    icu = keep(
        glob_java(os.path.join(ICU4J, "src", "main", "java", "android", "icu"))
        + glob_java(os.path.join(ICU4J, "libcore_bridge", "src", "java"))
    )
    for p in oj + libart + icu:
        if not os.path.isfile(p):
            raise SystemExit(f"missing source {p}")
    return oj, libart, icu


# --- class file helpers --------------------------------------------------------


def class_source_file(data):
    """Return (this_class internal name, SourceFile attribute or None)."""
    if data[:4] != b"\xca\xfe\xba\xbe":
        raise ValueError("not a class file")
    count = struct.unpack(">H", data[8:10])[0]
    pos, cp = 10, [None] * count
    i = 1
    while i < count:
        tag = data[pos]
        if tag == 1:
            ln = struct.unpack(">H", data[pos + 1:pos + 3])[0]
            cp[i] = data[pos + 3:pos + 3 + ln].decode("utf-8", "replace")
            pos += 3 + ln
        elif tag in (7, 8, 16, 19, 20):
            cp[i] = struct.unpack(">H", data[pos + 1:pos + 3])[0]
            pos += 3
        elif tag == 15:
            pos += 4
        elif tag in (3, 4, 9, 10, 11, 12, 17, 18):
            pos += 5
        elif tag in (5, 6):
            pos += 9
            i += 1
        else:
            raise ValueError(f"bad constant tag {tag}")
        i += 1
    this_class = cp[cp[struct.unpack(">H", data[pos + 2:pos + 4])[0]]]
    pos += 6
    n = struct.unpack(">H", data[pos:pos + 2])[0]
    pos += 2 + 2 * n

    def skip_members(pos):
        n = struct.unpack(">H", data[pos:pos + 2])[0]
        pos += 2
        for _ in range(n):
            pos += 6
            an = struct.unpack(">H", data[pos:pos + 2])[0]
            pos += 2
            for _ in range(an):
                pos += 2 + 4 + struct.unpack(">I", data[pos + 2:pos + 6])[0]
        return pos

    pos = skip_members(pos)
    pos = skip_members(pos)
    an = struct.unpack(">H", data[pos:pos + 2])[0]
    pos += 2
    for _ in range(an):
        name = cp[struct.unpack(">H", data[pos:pos + 2])[0]]
        ln = struct.unpack(">I", data[pos + 2:pos + 6])[0]
        if name == "SourceFile":
            return this_class, cp[struct.unpack(">H", data[pos + 6:pos + 8])[0]]
        pos += 6 + ln
    return this_class, None


def source_key(path):
    """Key 'pkg/dir/File.java' of a source file, from its package declaration."""
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    m = re.search(r"^\s*package\s+([\w.]+)\s*;", text, re.M)
    pkg = m.group(1).replace(".", "/") + "/" if m else ""
    return pkg + os.path.basename(path)


# --- steps ----------------------------------------------------------------------


def javac(args, argfile):
    with open(argfile, "w", encoding="utf-8", newline="\n") as f:
        for a in args:
            f.write('"' + a.replace("\\", "/") + '"\n')
    run(["javac", "@" + argfile])


def write_jar(path, entries):
    """entries: list of (arcname, bytes)."""
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in sorted(entries):
            z.writestr(zipfile.ZipInfo(name, date_time=(2008, 1, 1, 0, 0, 0)), data)


def d8(inputs, out_jar, libs=(), classpath=(), boot=False):
    # Soong dexes the core libraries with --android-platform-build (from
    # libcore_java_defaults). Release mode keeps line numbers; d8 --debug
    # would also add com.android.tools.r8.annotations.LambdaMethod to every
    # output, which then is defined in all three boot jars.
    mode = ["--release", "--android-platform-build"] if boot else ["--release"]
    cmd = ["java", "-Xmx4g", "-cp", D8_JAR, "com.android.tools.r8.D8"] + mode + [
           "--min-api", MIN_API, "--output", out_jar]
    for lib in libs:
        cmd += ["--lib", lib]
    for cp in classpath:
        cmd += ["--classpath", cp]
    cmd += list(inputs)
    run(cmd)


def build_boot():
    oj, libart, icu = source_sets()
    gen = os.path.join(OUT, "gen")
    if os.path.isdir(gen):
        shutil.rmtree(gen)
    aconfig_libart = os.path.join(gen, "aconfig-libart")
    aconfig_icu = os.path.join(gen, "aconfig-icu")
    run([sys.executable, "-I", os.path.join(HERE, "gen_aconfig.py"), aconfig_libart,
         os.path.join(LIBCORE, "libcore.aconfig"),
         os.path.join(AOSP, "art", "build", "flags", "art-flags.aconfig")])
    run([sys.executable, "-I", os.path.join(HERE, "gen_aconfig.py"), aconfig_icu,
         os.path.join(AOSP, "external", "icu", "icu.aconfig")])
    libart += glob_java(aconfig_libart)
    icu += glob_java(aconfig_icu)
    # Compile-only: our annotation stubs and ICU's own icu-neverinline-stub.
    # Soong's jarjar rule renames NeverInline to
    # dalvik.annotation.optimization.NeverInline in core-icu4j; that only
    # guides the AOT/JIT inliner and is not reproduced here.
    stubs = glob_java(os.path.join(HERE, "stubs")) + glob_java(os.path.join(ICU4J, "stub"))
    module_info = os.path.join(LIBCORE, "luni", "src", "module", "java", "module-info.java")
    log(f"sources: core-oj {len(oj)}, core-libart {len(libart)}, core-icu4j {len(icu)}, "
        f"compile-only stubs {len(stubs)}")

    classes = os.path.join(OUT, "classes", "boot")
    if os.path.isdir(classes):
        shutil.rmtree(classes)
    os.makedirs(classes)
    args = [
        "-encoding", "UTF-8",
        "-source", JAVA_VERSION, "-target", JAVA_VERSION,
        "--system=none",
        "--patch-module=java.base=.",
        "-XDstringConcat=inline",
        "-g",
        "-nowarn", "-Xlint:none", "-Xmaxerrs", "500",
        "-proc:none",
        "-d", classes,
        module_info,
    ] + oj + libart + icu + stubs
    javac(args, os.path.join(OUT, "javac-boot.args"))

    # Split the classes by the library their source file belongs to.
    owner = {}
    for lib, files in (("core-oj", oj), ("core-libart", libart), ("core-icu4j", icu), ("stub", stubs)):
        for p in files:
            k = source_key(p)
            if k in owner and owner[k] != lib:
                raise SystemExit(f"{k} is in both {owner[k]} and {lib}")
            owner[k] = lib
    per_lib = {"core-oj": [], "core-libart": [], "core-icu4j": [], "stub": []}
    for d, _, files in os.walk(classes):
        for f in files:
            if not f.endswith(".class") or f == "module-info.class":
                continue
            with open(os.path.join(d, f), "rb") as fh:
                data = fh.read()
            name, src = class_source_file(data)
            pkg = name.rsplit("/", 1)[0] + "/" if "/" in name else ""
            key = pkg + (src or name.split("/")[-1].split("$")[0] + ".java")
            lib = owner.get(key)
            if lib is None:
                raise SystemExit(f"cannot place class {name} (source {key})")
            per_lib[lib].append((name + ".class", data))

    jars = {}
    for lib in ("core-oj", "core-libart", "core-icu4j"):
        cj = os.path.join(OUT, "classes", lib + "-classes.jar")
        write_jar(cj, per_lib[lib])
        jars[lib] = cj
        log(f"{lib}: {len(per_lib[lib])} classes")
    log(f"compile-only stubs dropped: {len(per_lib['stub'])} classes")

    resources = collect_resources()
    for lib in ("core-oj", "core-libart", "core-icu4j"):
        out_jar = os.path.join(OUT, lib + ".jar")
        tmp = out_jar + ".d8.jar"
        others = [jars[o] for o in jars if o != lib]
        d8([jars[lib]], tmp, classpath=others, boot=True)
        entries = []
        with zipfile.ZipFile(tmp) as z:
            for n in z.namelist():
                entries.append((n, z.read(n)))
        if lib == "core-oj":
            entries += resources
        write_jar(out_jar, entries)
        os.remove(tmp)
        log(f"wrote {out_jar} ({os.path.getsize(out_jar)} bytes)")
    return jars


def collect_resources():
    """java_resources of core-oj: core-luni-resources and core-ojluni-resources."""
    entries = []
    luni = os.path.join(LIBCORE, "luni", "src", "main", "java")
    for rel in ("java/util/logging/logging.properties", "java/security/security.properties"):
        with open(os.path.join(luni, *rel.split("/")), "rb") as f:
            entries.append((rel, f.read()))
    res = os.path.join(LIBCORE, "ojluni", "src", "main", "resources")
    for d, _, files in os.walk(res):
        for f in files:
            p = os.path.join(d, f)
            with open(p, "rb") as fh:
                entries.append((os.path.relpath(p, res).replace(os.sep, "/"), fh.read()))
    return entries


def build_tests(jars):
    classes = os.path.join(OUT, "classes", "tests")
    if os.path.isdir(classes):
        shutil.rmtree(classes)
    os.makedirs(classes)
    boot_classes = os.path.join(OUT, "classes", "boot")
    for name in ("Hello", "Bench", "Faults", "JniStress"):
        javac([
            "-encoding", "UTF-8",
            "-source", JAVA_VERSION, "-target", JAVA_VERSION,
            "--system=none",
            "--module-path", boot_classes,
            "-XDstringConcat=inline",
            "-nowarn",
            "-d", classes,
            os.path.join(HERE, "src", name + ".java"),
        ], os.path.join(OUT, f"javac-{name}.args"))
        cj = os.path.join(classes, name + "-classes.jar")
        entries = []
        for f in os.listdir(classes):
            if f.startswith(name) and f.endswith(".class"):
                with open(os.path.join(classes, f), "rb") as fh:
                    entries.append((f, fh.read()))
        write_jar(cj, entries)
        out = os.path.join(OUT, name.lower() + ".dex")
        if os.path.isdir(out):
            shutil.rmtree(out)
        tmp = os.path.join(OUT, name.lower() + ".d8.jar")
        d8([cj], tmp, libs=list(jars.values()))
        with zipfile.ZipFile(tmp) as z:
            data = z.read("classes.dex")
        os.remove(tmp)
        with open(out, "wb") as f:
            f.write(data)
        log(f"wrote {out} ({len(data)} bytes)")


def main(argv):
    ensure_build_tools()
    os.makedirs(OUT, exist_ok=True)
    if "--tests-only" in argv:
        # Reuse the boot jars already built.
        jars = {j: os.path.join(OUT, "classes", j + "-classes.jar")
                for j in ("core-oj", "core-libart", "core-icu4j")}
    else:
        jars = build_boot()
    build_tests(jars)
    if "--skip-verify" not in argv:
        run([sys.executable, "-I", os.path.join(HERE, "verify_boot.py")])


if __name__ == "__main__":
    main(sys.argv)
