"""Generate Java flag classes for aconfig declaration files.

Soong generates, for each java_aconfig_library, a package holding Flags,
FeatureFlags and FeatureFlagsImpl. This script writes a small equivalent in
which every flag is fixed at the value it has when no release configuration
sets it: disabled. The native side of spike S1 makes the same choice, so Java
and native code agree on every flag.

Usage: gen_aconfig.py <out_dir> <file.aconfig>...
"""

import os
import re
import sys


def parse(path):
    """Return (package, [flag names]) of one .aconfig text proto file."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    # Drop comments; descriptions may contain '#', so only strip from the
    # start of a line or after whitespace outside strings would be exact,
    # but aconfig files at this tag keep comments on their own lines.
    lines = [ln for ln in text.splitlines() if not ln.lstrip().startswith("#")]
    text = "\n".join(lines)
    m = re.search(r'^\s*package:\s*"([^"]+)"', text, re.M)
    if not m:
        raise SystemExit(f"{path}: no package")
    package = m.group(1)
    names = []
    for block in re.finditer(r"\bflag\s*\{", text):
        # Find the matching brace of this flag block.
        depth = 0
        i = block.end() - 1
        while True:
            c = text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    break
            elif c == '"':
                i = text.index('"', i + 1)
            i += 1
        body = text[block.end():i]
        nm = re.search(r'^\s*name:\s*"([^"]+)"', body, re.M)
        if not nm:
            raise SystemExit(f"{path}: flag without name")
        names.append(nm.group(1))
    return package, names


def camel(name):
    parts = name.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def emit(out_dir, package, names):
    pkg_dir = os.path.join(out_dir, *package.split("."))
    os.makedirs(pkg_dir, exist_ok=True)
    header = (
        "// Generated by spikes/s1/java/gen_aconfig.py. Every flag is fixed at\n"
        "// its default value (disabled).\n"
        f"package {package};\n\n"
    )
    flags = [header, "/** @hide */\npublic final class Flags {\n"]
    iface = [header, "/** @hide */\npublic interface FeatureFlags {\n"]
    impl = [header, "/** @hide */\npublic final class FeatureFlagsImpl implements FeatureFlags {\n"]
    for n in names:
        const = "FLAG_" + n.upper()
        m = camel(n)
        flags.append(f'    public static final String {const} = "{package}.{n}";\n')
        flags.append(f"    public static boolean {m}() {{\n        return false;\n    }}\n")
        iface.append(f"    boolean {m}();\n")
        impl.append(f"    @Override\n    public boolean {m}() {{\n        return false;\n    }}\n")
    flags.append("    private Flags() {}\n}\n")
    iface.append("}\n")
    impl.append("}\n")
    for fname, body in (("Flags", flags), ("FeatureFlags", iface), ("FeatureFlagsImpl", impl)):
        with open(os.path.join(pkg_dir, fname + ".java"), "w", encoding="utf-8", newline="\n") as f:
            f.write("".join(body))


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    out_dir = argv[1]
    by_pkg = {}
    for path in argv[2:]:
        package, names = parse(path)
        by_pkg.setdefault(package, []).extend(names)
    for package, names in sorted(by_pkg.items()):
        emit(out_dir, package, sorted(set(names)))
        print(f"aconfig: {package}: {len(set(names))} flags")


if __name__ == "__main__":
    main(sys.argv)
